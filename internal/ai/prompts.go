func fieldKeyStrings() []string {
	out := make([]string, len(model.FieldKeys))
	for i, k := range model.FieldKeys {
		out[i] = string(k)
	}
	return out
}

func inputTypeStrings() []string {
	out := make([]string, len(model.InputTypes))
	for i, t := range model.InputTypes {
		out[i] = string(t)
	}
	return out
}


package ai

import "testing"

// Подсказки с выдуманными контактами и цифрами не доходят до кнопок; подсказки из источника остаются.
func TestGuardSuggestions(t *testing.T) {
	src := "Колледж, растёт число отчислений на 1 курсе, кураторы групп и завуч Айгуль"
	got := guardSuggestions([]string{"Завуч Иванова И.И., почта ivanova@college.ru", "За последние 2 года растёт число отчислений", "Кураторы групп и завуч", "Завуч Айгуль"}, src)
	if len(got) != 2 || got[0] != "Кураторы групп и завуч" || got[1] != "Завуч Айгуль" {
		t.Fatalf("got %q", got)
	}
}
